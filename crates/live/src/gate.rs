//! The command gate. Every command id is in exactly one of four tables:
//!
//! - [`FREE`]: runs now; its changes are shared as free writes (cells, formats, sizes, hidden).
//! - [`ORDERED`]: changes the rows or columns themselves; runs through the structure lock (G9).
//! - [`LOCAL`]: changes nothing shared (selection, view, windows, files, clipboard, queries).
//! - [`NOT_YET`]: a later milestone shares it; refused while editing live with [`NOT_YET_TEXT`].
//!
//! An id in no table (a command added later) is refused like [`NOT_YET`]. The tables are checked
//! against the engine's command list and the ribbon catalog by a test, so a new command cannot
//! slip through unclassified. Running an unshared command anyway (bypassing the gate) is caught
//! after the fact by the safety net in `GridApp::local`.

/// What the user sees when a command is not shared yet.
pub const NOT_YET_TEXT: &str = "Not available while editing live yet";

/// Which table an id is in.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Class {
    Free,
    Ordered,
    Local,
    NotYet,
}

/// The table `id` is in; an unknown id is [`Class::NotYet`].
#[must_use]
pub fn class(id: &str) -> Class {
    if FREE.binary_search(&id).is_ok() {
        Class::Free
    } else if ORDERED.binary_search(&id).is_ok() {
        Class::Ordered
    } else if LOCAL.binary_search(&id).is_ok() {
        Class::Local
    } else {
        Class::NotYet
    }
}

/// How many of the four tables hold `id` (a test wants exactly one).
#[must_use]
pub fn tables_holding(id: &str) -> usize {
    [FREE, ORDERED, LOCAL, NOT_YET].iter().filter(|t| t.binary_search(&id).is_ok()).count()
}


